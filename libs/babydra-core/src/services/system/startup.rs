//! Startup commands service (Labwc autostart).

use crate::error::CoreResult;
use crate::models::startup_command::StartupCommand;
use crate::services::utils::{get_home_dir, set_unix_mode};
use std::fs;
use std::path::{Path, PathBuf};

/// Gets the path to the labwc autostart configuration file.
fn get_autostart_path() -> PathBuf {
    let home = get_home_dir();
    let user_config = Path::new(&home).join(".config/labwc/autostart");
    if user_config.exists() {
        return user_config;
    }

    // Check project workspace fallback
    let assets_config = Path::new("assets/configs/labwc/autostart");
    if assets_config.exists() {
        return assets_config.to_path_buf();
    }
    let local_config = Path::new("configs/labwc/autostart");
    if local_config.exists() {
        return local_config.to_path_buf();
    }

    user_config
}

/// Retrieves list of autostart commands from labwc autostart file.
pub fn get_startup_commands() -> Vec<StartupCommand> {
    let config_path = get_autostart_path();
    let mut commands = Vec::new();

    if let Ok(content) = fs::read_to_string(&config_path) {
        let mut id_counter = 1;
        let mut pending_name: Option<String> = None;
        for line in content.lines() {
            let trim = line.trim();
            if trim.is_empty() {
                continue;
            }
            if let Some(comment) = trim.strip_prefix('#') {
                let c_trim = comment.trim();
                if let Some(n) = c_trim.strip_prefix("name:") {
                    pending_name = Some(n.trim().to_string());
                } else if !c_trim.starts_with('!')
                    && !c_trim.to_lowercase().contains("autostart configuration")
                    && !c_trim.to_lowercase().contains("auto-generated")
                    && !c_trim.is_empty()
                {
                    pending_name = Some(c_trim.to_string());
                }
                continue;
            }

            let name = pending_name.take();
            if trim.starts_with("exec-once") {
                if let Some((_, cmd)) = trim.split_once('=') {
                    commands.push(StartupCommand {
                        id: id_counter,
                        name,
                        command: cmd.trim().to_string(),
                    });
                    id_counter += 1;
                }
            } else {
                commands.push(StartupCommand {
                    id: id_counter,
                    name,
                    command: trim.to_string(),
                });
                id_counter += 1;
            }
        }
    }

    commands
}

/// Saves autostart commands to labwc autostart file.
pub fn save_startup_cmds(commands: &[StartupCommand]) -> CoreResult<()> {
    let home = get_home_dir();
    let user_config = Path::new(&home).join(".config/labwc/autostart");

    if let Some(parent) = user_config.parent() {
        let _ = fs::create_dir_all(parent);
    }

    let mut content = String::from(
        "#!/bin/bash\n# Autostart configuration for labwc with BabyDra shell\n# Auto-generated by Settings\n\n",
    );
    for cmd in commands {
        let trimmed = cmd.command.trim();
        if !trimmed.is_empty() {
            if let Some(ref name) = cmd.name {
                let name_trim = name.trim();
                if !name_trim.is_empty() {
                    content.push_str(&format!("# name: {}\n", name_trim));
                }
            }
            content.push_str(&format!("{}\n", trimmed));
        }
    }

    fs::write(&user_config, &content).map_err(|e| e.to_string())?;
    let _ = set_unix_mode(&user_config, 0o755);

    Ok(())
}

/// Adds a new startup command with optional mnemonic name.
pub fn add_startup_cmd(name: Option<String>, command: &str) -> CoreResult<()> {
    let mut cmds = get_startup_commands();
    let next_id = cmds.iter().map(|c| c.id).max().unwrap_or(0) + 1;
    cmds.push(StartupCommand {
        id: next_id,
        name,
        command: command.trim().to_string(),
    });
    save_startup_cmds(&cmds)
}

/// Deletes a startup command by its ID.
pub fn delete_startup_cmd(id: u32) -> CoreResult<()> {
    let mut cmds = get_startup_commands();
    cmds.retain(|c| c.id != id);
    save_startup_cmds(&cmds)
}

/// Updates an existing startup command by its ID.
pub fn update_startup_cmd(id: u32, name: Option<String>, command: &str) -> CoreResult<()> {
    let mut cmds = get_startup_commands();
    if let Some(cmd) = cmds.iter_mut().find(|c| c.id == id) {
        cmd.name = name;
        cmd.command = command.trim().to_string();
        save_startup_cmds(&cmds)
    } else {
        Err(format!("Startup command with ID {} not found", id).into())
    }
}

